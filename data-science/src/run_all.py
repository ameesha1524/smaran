"""Every table and figure, in one command: `make ds` (or `python src/run_all.py`).

  SMARAN_DS_SMALL=1   the cut-down cohort (48 patients, 300 days), the version CI runs
  SMARAN_DS_BOOT=200  fewer bootstrap resamples (the default, 1000, is what the committed results used)
  SMARAN_DS_RESULTS=dir  write somewhere other than results/

Writes results/*.csv, results/figures/*.png (each with a .json sidecar holding the seed and parameters),
results/run_info.json (versions, seed, wall time per step) and results/SUMMARY.md (the headline tables).
"""

